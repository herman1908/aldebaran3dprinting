-- Skema database Supabase untuk Aldebaran3DPrinting.
-- Cara pakai: Supabase Dashboard > SQL Editor > New query > tempel semua > Run.
-- Setelah itu isi environment variables:
--   SUPABASE_URL          = https://<project-ref>.supabase.co
--   SUPABASE_SERVICE_KEY  = service_role key (Settings > API)  [RAHASIA, server-side saja]
--   APP_SECRET            = teks acak panjang (agar cookie login tetap valid antar-deploy)

/* ---------- Produk ---------- */
create table if not exists produk (
    id          bigint primary key,
    nama        text   not null default '',
    penjual     text   not null default 'Aldebaran Studio',
    kategori    jsonb  not null default '[]'::jsonb,
    warna       text   not null default 'koral',
    harga       integer not null default 0,
    unduhan     integer not null default 0,
    suka        integer not null default 0,
    gambar      text   not null default '',
    galeri      jsonb  not null default '[]'::jsonb,
    deskripsi   text   not null default '',
    terlaris    boolean not null default false,
    unggulan    boolean not null default false,
    dibuat      timestamptz not null default now(),
    diperbarui  timestamptz not null default now()
);

/* ---------- Media sosial ---------- */
create table if not exists sosmed (
    id        bigint primary key,
    platform  text not null default 'website',
    label     text not null default '',
    url       text not null default '',
    dibuat    timestamptz not null default now()
);

/* ---------- Pesan / chat konsumen ---------- */
create table if not exists pesan (
    id      bigint generated by default as identity primary key,
    nama    text not null default '',
    hp      text not null default '',
    email   text not null default '',
    pesan   text not null default '',
    dibaca  boolean not null default false,
    waktu   timestamptz not null default now()
);

create index if not exists idx_pesan_belum
    on pesan (dibaca, waktu desc);

/* ---------- Statistik checkout (dasar "Terlaris") ---------- */
create table if not exists checkout_stat (
    produk_id bigint primary key references produk(id) on delete cascade,
    jumlah    bigint not null default 0
);

/* ---------- Pengaturan kecil (flag seed, dll.) ---------- */
create table if not exists pengaturan (
    kunci text primary key,
    nilai text not null default ''
);

/* ---------- Akun admin (password hashed, bisa diganti dari panel) ---------- */
create table if not exists admin_akun (
    id            integer primary key default 1 check (id = 1),
    password_hash text not null,
    diperbarui    timestamptz not null default now()
);

/* ---------- Trigger: perbarui kolom diperbarui ---------- */
create or replace function set_diperbarui()
returns trigger
language plpgsql
as $$
begin
    new.diperbarui = now();
    return new;
end;
$$;

drop trigger if exists trg_produk_diperbarui on produk;
create trigger trg_produk_diperbarui
    before update on produk
    for each row execute function set_diperbarui();

/* ---------- RPC: tambah 1 hitungan checkout secara atomik ---------- */
create or replace function checkout_tambah_stat(p_id bigint)
returns void
language sql
security definer
set search_path = public
as $$
    insert into checkout_stat (produk_id, jumlah)
    values (p_id, 1)
    on conflict (produk_id) do update
        set jumlah = checkout_stat.jumlah + 1;
$$;

revoke all on function checkout_tambah_stat(bigint) from public, anon, authenticated;
grant execute on function checkout_tambah_stat(bigint) to service_role;

/* ---------- Hak akses ---------- */
grant usage on schema public to anon, authenticated, service_role;
grant all privileges on all tables in schema public to anon, authenticated, service_role;
grant all privileges on all sequences in schema public to anon, authenticated, service_role;

/* ---------- RLS: anon/authenticated tidak bisa akses langsung ----------
   PHP memakai service_role key yang melewati RLS. Tanpa policy, akses
   langsung dari browser (anon key) akan ditolak. */
alter table produk        enable row level security;
alter table sosmed        enable row level security;
alter table pesan         enable row level security;
alter table checkout_stat enable row level security;
alter table pengaturan    enable row level security;
alter table admin_akun    enable row level security;
